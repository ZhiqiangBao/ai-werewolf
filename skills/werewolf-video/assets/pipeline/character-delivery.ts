export function characterVoiceDirection(theme: string, seat: number) {
  const characters = characterVoices[theme as AvatarTheme], style = themes[theme as AvatarTheme];
  const character = characters?.[seat - 1], direction = style?.characters[seat - 1];
  if (!character || !direction) throw Error(`Missing character voice direction for ${theme} seat ${seat}`);
  const [persona, voice, rate] = direction;
  const designPrompt = `${character.gender}性，${character.appearance}，${persona}。${style.setting}。${voice}${style.delivery}干净单人声，无配乐、混响或音效。`;
  if (Array.from(designPrompt).length > 500) throw Error('Character voice design exceeds 500 characters');
  return { persona, appearance: character.appearance, gender: character.gender, rate, designPrompt,
    instruction: `表演设定：${style.setting}，${character.appearance}，${persona}。${voice}${style.delivery}只读给定原文，不改写台词，不增添称呼、语气词或内容。` };
}

/** Only apply when creating a project or when the maker explicitly redesigns its cast. */
export function applyCharacterDelivery(catalog: VoiceCatalog, cast: Cast[], theme: string): VoiceCatalog {
  const profiles = { ...catalog.profiles };
  for (const member of cast) {
    const direction = characterVoiceDirection(theme, member.seat), previous = profiles[member.voiceKey];
    if (!previous) throw Error(`Missing voice profile for ${member.voiceKey}`);
    profiles[member.voiceKey] = { ...previous, label: `${member.seat}号 ${direction.persona}`, rate: direction.rate, instruction: direction.instruction };
  }
  return { ...catalog, profiles };
}
